package fr.granulometrie.repo;

import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.Timestamp;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

import javax.imageio.ImageIO;

import fr.granulometrie.core.AnalysisParameters;
import fr.granulometrie.core.AnalysisResult;
import fr.granulometrie.core.Particle;
import fr.granulometrie.core.SizeStatistics;

/**
 * Persistance locale des analyses dans une base H2 embarquee.
 *
 * <p>Ce choix remplace le serveur MySQL de la version d'origine : aucune
 * installation externe n'est necessaire, la base est creee automatiquement dans
 * le dossier personnel de l'utilisateur ({@code ~/.granulometrie-studio}).</p>
 */
public final class AnalysisRepository implements AutoCloseable {

    private final Connection connection;
    private final Path databaseFile;

    /** Cree le depot avec la base par defaut (dossier utilisateur). */
    public AnalysisRepository() {
        this(defaultDatabaseFile());
    }

    /**
     * Cree le depot sur un fichier de base donne (utile pour les tests).
     *
     * @param databaseFile chemin du fichier de base, sans extension
     */
    public AnalysisRepository(Path databaseFile) {
        try {
            Class.forName("org.h2.Driver");
            Path absolute = databaseFile.toAbsolutePath();
            if (absolute.getParent() != null) {
                Files.createDirectories(absolute.getParent());
            }
            this.databaseFile = absolute;
            String url = "jdbc:h2:file:" + absolute + ";DB_CLOSE_ON_EXIT=FALSE";
            this.connection = DriverManager.getConnection(url, "sa", "");
            createSchema();
        } catch (Exception e) {
            throw new DataAccessException("Impossible d'ouvrir la base locale : " + e.getMessage(), e);
        }
    }

    /** @return l'emplacement par defaut de la base. */
    public static Path defaultDatabaseFile() {
        return Paths.get(System.getProperty("user.home"), ".granulometrie-studio", "history");
    }

    private void createSchema() throws SQLException {
        try (Statement st = connection.createStatement()) {
            st.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS session (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      created_at TIMESTAMP NOT NULL,
                      image_name VARCHAR(512),
                      image_width INT,
                      image_height INT,
                      pixel_size DOUBLE,
                      threshold_mode VARCHAR(32),
                      threshold_used INT,
                      blur_radius INT,
                      min_diameter DOUBLE,
                      max_diameter DOUBLE,
                      min_circularity DOUBLE,
                      exclude_border BOOLEAN,
                      particle_count INT,
                      d10 DOUBLE,
                      d50 DOUBLE,
                      d90 DOUBLE,
                      mean_diameter DOUBLE,
                      comment VARCHAR(4000),
                      image_blob BLOB
                    )
                    """);
            st.executeUpdate("""
                    CREATE TABLE IF NOT EXISTS grain (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      session_id BIGINT NOT NULL,
                      grain_index INT,
                      area DOUBLE,
                      perimeter DOUBLE,
                      centroid_x DOUBLE,
                      centroid_y DOUBLE,
                      bbox_x INT,
                      bbox_y INT,
                      bbox_w INT,
                      bbox_h INT,
                      major_axis DOUBLE,
                      minor_axis DOUBLE,
                      orientation DOUBLE,
                      circularity DOUBLE,
                      eq_diameter DOUBLE,
                      touches_border BOOLEAN,
                      CONSTRAINT fk_session FOREIGN KEY (session_id)
                        REFERENCES session(id) ON DELETE CASCADE
                    )
                    """);
            st.executeUpdate("CREATE INDEX IF NOT EXISTS idx_grain_session ON grain(session_id)");
        }
    }

    /**
     * Enregistre une analyse complete.
     *
     * @param result  resultat a enregistrer
     * @param comment commentaire libre de l'operateur
     * @return l'identifiant de la session creee
     */
    public long save(AnalysisResult result, String comment) {
        SizeStatistics stats = result.getStatistics();
        BufferedImage image = result.getImage();
        String sql = """
                INSERT INTO session (created_at, image_name, image_width, image_height, pixel_size,
                  threshold_mode, threshold_used, blur_radius, min_diameter, max_diameter,
                  min_circularity, exclude_border, particle_count, d10, d50, d90, mean_diameter,
                  comment, image_blob)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                """;
        try {
            connection.setAutoCommit(false);
            long sessionId;
            try (PreparedStatement ps = connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
                AnalysisParameters p = result.getParameters();
                ps.setTimestamp(1, Timestamp.valueOf(LocalDateTime.now()));
                ps.setString(2, result.getImageName());
                ps.setInt(3, result.getWidth());
                ps.setInt(4, result.getHeight());
                ps.setDouble(5, p.getPixelSizeMicrons());
                ps.setString(6, p.isManualThreshold() ? "manuel" : "otsu");
                ps.setInt(7, result.getThresholdUsed());
                ps.setInt(8, p.getBlurRadius());
                ps.setDouble(9, p.getMinDiameter());
                ps.setDouble(10, p.getMaxDiameter());
                ps.setDouble(11, p.getMinCircularity());
                ps.setBoolean(12, p.isExcludeBorder());
                ps.setInt(13, stats.count());
                ps.setDouble(14, stats.d10());
                ps.setDouble(15, stats.d50());
                ps.setDouble(16, stats.d90());
                ps.setDouble(17, stats.meanDiameter());
                ps.setString(18, comment == null ? "" : comment);
                ps.setBytes(19, toPng(image));
                ps.executeUpdate();
                try (ResultSet keys = ps.getGeneratedKeys()) {
                    keys.next();
                    sessionId = keys.getLong(1);
                }
            }
            insertGrains(sessionId, result.getParticles());
            connection.commit();
            return sessionId;
        } catch (SQLException | IOException e) {
            rollbackQuietly();
            throw new DataAccessException("Enregistrement impossible : " + e.getMessage(), e);
        } finally {
            resetAutoCommit();
        }
    }

    private void insertGrains(long sessionId, List<Particle> particles) throws SQLException {
        String sql = """
                INSERT INTO grain (session_id, grain_index, area, perimeter, centroid_x, centroid_y,
                  bbox_x, bbox_y, bbox_w, bbox_h, major_axis, minor_axis, orientation, circularity,
                  eq_diameter, touches_border)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                """;
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            for (Particle particle : particles) {
                ps.setLong(1, sessionId);
                ps.setInt(2, particle.id());
                ps.setDouble(3, particle.area());
                ps.setDouble(4, particle.perimeter());
                ps.setDouble(5, particle.centroidX());
                ps.setDouble(6, particle.centroidY());
                ps.setInt(7, particle.bboxX());
                ps.setInt(8, particle.bboxY());
                ps.setInt(9, particle.bboxWidth());
                ps.setInt(10, particle.bboxHeight());
                ps.setDouble(11, particle.majorAxis());
                ps.setDouble(12, particle.minorAxis());
                ps.setDouble(13, particle.orientationDegrees());
                ps.setDouble(14, particle.circularity());
                ps.setDouble(15, particle.equivalentDiameter());
                ps.setBoolean(16, particle.touchesBorder());
                ps.addBatch();
            }
            ps.executeBatch();
        }
    }

    /** @return les sessions enregistrees, de la plus recente a la plus ancienne. */
    public List<StoredSession> listSessions() {
        String sql = """
                SELECT id, created_at, image_name, image_width, image_height, pixel_size,
                       threshold_mode, threshold_used, blur_radius, min_diameter, max_diameter,
                       min_circularity, exclude_border, particle_count, d10, d50, d90,
                       mean_diameter, comment
                FROM session ORDER BY created_at DESC, id DESC
                """;
        List<StoredSession> sessions = new ArrayList<>();
        try (Statement st = connection.createStatement(); ResultSet rs = st.executeQuery(sql)) {
            while (rs.next()) {
                sessions.add(new StoredSession(
                        rs.getLong("id"),
                        rs.getTimestamp("created_at").toLocalDateTime(),
                        rs.getString("image_name"),
                        rs.getInt("image_width"),
                        rs.getInt("image_height"),
                        readParameters(rs),
                        rs.getInt("threshold_used"),
                        rs.getInt("particle_count"),
                        rs.getDouble("d10"),
                        rs.getDouble("d50"),
                        rs.getDouble("d90"),
                        rs.getDouble("mean_diameter"),
                        rs.getString("comment"),
                        null,
                        null));
            }
        } catch (SQLException e) {
            throw new DataAccessException("Lecture de l'historique impossible : " + e.getMessage(), e);
        }
        return sessions;
    }

    /**
     * Charge une session complete (image + particules).
     *
     * @param id identifiant de la session
     * @return la session, ou null si elle n'existe plus
     */
    public StoredSession loadSession(long id) {
        String sql = "SELECT * FROM session WHERE id = ?";
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setLong(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    return null;
                }
                byte[] blob = rs.getBytes("image_blob");
                BufferedImage image = null;
                if (blob != null) {
                    image = ImageIO.read(new ByteArrayInputStream(blob));
                }
                return new StoredSession(
                        rs.getLong("id"),
                        rs.getTimestamp("created_at").toLocalDateTime(),
                        rs.getString("image_name"),
                        rs.getInt("image_width"),
                        rs.getInt("image_height"),
                        readParameters(rs),
                        rs.getInt("threshold_used"),
                        rs.getInt("particle_count"),
                        rs.getDouble("d10"),
                        rs.getDouble("d50"),
                        rs.getDouble("d90"),
                        rs.getDouble("mean_diameter"),
                        rs.getString("comment"),
                        image,
                        readGrains(id));
            }
        } catch (SQLException | IOException e) {
            throw new DataAccessException("Chargement de la session impossible : " + e.getMessage(), e);
        }
    }

    private List<Particle> readGrains(long sessionId) throws SQLException {
        String sql = "SELECT * FROM grain WHERE session_id = ? ORDER BY grain_index";
        List<Particle> particles = new ArrayList<>();
        try (PreparedStatement ps = connection.prepareStatement(sql)) {
            ps.setLong(1, sessionId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    particles.add(new Particle(
                            rs.getInt("grain_index"),
                            rs.getDouble("area"),
                            rs.getDouble("perimeter"),
                            rs.getDouble("centroid_x"),
                            rs.getDouble("centroid_y"),
                            rs.getInt("bbox_x"),
                            rs.getInt("bbox_y"),
                            rs.getInt("bbox_w"),
                            rs.getInt("bbox_h"),
                            rs.getDouble("major_axis"),
                            rs.getDouble("minor_axis"),
                            rs.getDouble("orientation"),
                            rs.getDouble("circularity"),
                            rs.getDouble("eq_diameter"),
                            rs.getBoolean("touches_border")));
                }
            }
        }
        return particles;
    }

    /**
     * Supprime une session et ses particules.
     *
     * @param id identifiant de la session
     */
    public void deleteSession(long id) {
        try {
            connection.setAutoCommit(false);
            try (PreparedStatement grains = connection.prepareStatement("DELETE FROM grain WHERE session_id = ?");
                 PreparedStatement session = connection.prepareStatement("DELETE FROM session WHERE id = ?")) {
                grains.setLong(1, id);
                grains.executeUpdate();
                session.setLong(1, id);
                session.executeUpdate();
            }
            connection.commit();
        } catch (SQLException e) {
            rollbackQuietly();
            throw new DataAccessException("Suppression impossible : " + e.getMessage(), e);
        } finally {
            resetAutoCommit();
        }
    }

    /** @return le nombre de sessions enregistrees. */
    public int count() {
        try (Statement st = connection.createStatement();
             ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM session")) {
            rs.next();
            return rs.getInt(1);
        } catch (SQLException e) {
            throw new DataAccessException("Comptage impossible : " + e.getMessage(), e);
        }
    }

    /** @return le fichier de base utilise. */
    public Path getDatabaseFile() {
        return databaseFile;
    }

    private AnalysisParameters readParameters(ResultSet rs) throws SQLException {
        AnalysisParameters p = new AnalysisParameters();
        p.setPixelSizeMicrons(rs.getDouble("pixel_size"));
        p.setManualThreshold("manuel".equalsIgnoreCase(rs.getString("threshold_mode")));
        p.setThreshold(rs.getInt("threshold_used"));
        p.setBlurRadius(rs.getInt("blur_radius"));
        p.setMinDiameter(rs.getDouble("min_diameter"));
        p.setMaxDiameter(rs.getDouble("max_diameter"));
        p.setMinCircularity(rs.getDouble("min_circularity"));
        p.setExcludeBorder(rs.getBoolean("exclude_border"));
        return p;
    }

    private static byte[] toPng(BufferedImage image) throws IOException {
        if (image == null) {
            return null;
        }
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        ImageIO.write(image, "png", out);
        return out.toByteArray();
    }

    private void rollbackQuietly() {
        try {
            connection.rollback();
        } catch (SQLException ignored) {
            // rien a faire : on remonte l'erreur initiale
        }
    }

    private void resetAutoCommit() {
        try {
            connection.setAutoCommit(true);
        } catch (SQLException ignored) {
            // fermeture imminente
        }
    }

    @Override
    public void close() {
        try {
            connection.close();
        } catch (SQLException ignored) {
            // fermeture best-effort
        }
    }

    /** Erreur d'acces a la base locale. */
    public static class DataAccessException extends RuntimeException {
        private static final long serialVersionUID = 1L;

        public DataAccessException(String message, Throwable cause) {
            super(message, cause);
        }
    }
}
